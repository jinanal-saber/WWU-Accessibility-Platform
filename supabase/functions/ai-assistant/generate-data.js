// Builds data.ts (what the AI assistant knows) from the website's own data files, so the
// assistant and the map can never drift apart. Run this from inside this folder whenever
// building-info.js or accessibility-data.js changes, then redeploy the function:
//
//     node generate-data.js            (reads ../../../user/*.js, i.e. the repo's user/ folder)
//     node generate-data.js path/to/user
//
// Nothing here is fetched from the internet; it only reads those files and the resource list below.

const fs = require("fs"), path = require("path"), vm = require("vm");
const userDir = path.resolve(process.argv[2] || path.join(__dirname, "..", "..", "..", "user"));
const read = f => fs.readFileSync(path.join(userDir, f), "utf8");

function load(file, exportName) {
    const ctx = {}; vm.createContext(ctx);
    vm.runInContext(read(file) + `\nthis.__out = ${exportName};`, ctx);
    return ctx.__out;
}

const info = load("building-info.js", "WWU_BUILDING_INFO");
const checked = load("building-info.js", "WWU_BUILDING_INFO_CHECKED");
const features = load("accessibility-data.js", "ACCESSIBILITY_FEATURES");
const featuresSource = load("accessibility-data.js", "ACCESSIBILITY_DATA_SOURCE");

// building code -> full name, taken from the names the site already uses, e.g. "Miller Hall (MH)"
const names = {};
for (const m of read("make_report.js").matchAll(/"([^"\n]*\(([A-Z]{2,3})\))"/g)) names[m[2]] = m[1].replace(/\s*\([A-Z]{2,3}\)\s*$/, "");

const buildings = Object.keys(info).sort().map(code => ({
    code,
    name: names[code] || code,
    url: info[code].url,
    accessibility: info[code].accessibility,
    genderNeutral: info[code].genderNeutral || null,
    note: info[code].note || null,
    source: info[code].source,
}));

// Map-layer points: only the kinds that are meaningful as text. The ~120 route points are single
// dots on a line with no useful words, so they're left out.
const LAYERS = [
    ["accessible_entrance", "Accessible entrances"],
    ["accessible_parking", "Accessible parking"],
    ["elevator", "Elevators"],
    ["accessible_restroom", "Accessible restrooms (listed on WWU's map as gender-neutral and tagged accessible)"],
];
const clean = s => String(s || "").replace(/\s+/g, " ").trim().slice(0, 140);
const layerLines = LAYERS.map(([type, label]) => {
    const counts = new Map();
    for (const f of features.filter(x => x.type === type)) {
        const key = clean(f.title) + (clean(f.description) ? " — " + clean(f.description) : "");
        counts.set(key, (counts.get(key) || 0) + 1);
    }
    return { label, items: [...counts.entries()].map(([text, n]) => n > 1 ? `${text} (x${n})` : text) };
});

