const out =
`// AUTO-GENERATED by generate-data.js from the website's data files. Do not edit by hand:
// change user/building-info.js or user/accessibility-data.js, re-run generate-data.js, and redeploy.

export const DATA_CHECKED: string = ${JSON.stringify(checked)};
export const MAP_DATA_SOURCE: string = ${JSON.stringify(featuresSource)};

export const BUILDINGS: { code: string; name: string; url: string; accessibility: string[]; genderNeutral: string | null; note: string | null; source: string }[] = ${JSON.stringify(buildings, null, 1)};

export const LAYER_LINES: { label: string; items: string[] }[] = ${JSON.stringify(layerLines, null, 1)};

export const RESOURCES: { id: string; name: string; url: string; about: string }[] = ${JSON.stringify(resources, null, 1)};
`;
fs.writeFileSync(path.join(__dirname, "data.ts"), out);
console.log(`data.ts written: ${buildings.length} buildings, ${layerLines.map(l => l.items.length).reduce((a, b) => a + b, 0)} map-layer lines, ${resources.length} resources (${out.length} bytes)`);
